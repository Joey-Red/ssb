#!/usr/bin/env node
import { spawnSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptPath = fileURLToPath(import.meta.url)
const repoRoot = resolve(dirname(scriptPath), '..')
const defaultReviewDir = resolve(repoRoot, 'src/data/proLabReviews')
const defaultIndexPath = resolve(defaultReviewDir, 'index.ts')

const isObject = (value) => value !== null && typeof value === 'object' && !Array.isArray(value)

export function validateSubmissionEnvelope(value) {
  const errors = []
  if (!isObject(value)) return { submission: null, errors: ['Review submission JSON must be an object.'] }

  const vodId = typeof value.vodId === 'string' ? value.vodId.trim() : ''
  if (!vodId) errors.push('Review submission must include a non-empty vodId.')
  if (value.targetStatus !== 'annotated' && value.targetStatus !== 'reviewed') {
    errors.push('targetStatus must be annotated or reviewed.')
  }
  if (!Array.isArray(value.moments)) errors.push('moments must be an array.')
  if (!isObject(value.breakdown)) errors.push('breakdown must be an object.')
  if (isObject(value.breakdown) && value.breakdown.vodId !== vodId) {
    errors.push('breakdown.vodId must match submission vodId.')
  }

  if (Array.isArray(value.moments)) {
    const momentIds = new Set()
    for (const [index, moment] of value.moments.entries()) {
      if (!isObject(moment)) {
        errors.push(`moments[${index}] must be an object.`)
        continue
      }
      const momentId = typeof moment.id === 'string' ? moment.id.trim() : ''
      if (!momentId) errors.push(`moments[${index}] must include a non-empty id.`)
      else if (momentIds.has(momentId)) errors.push(`Duplicate moment id inside submission: ${momentId}.`)
      else momentIds.add(momentId)
      if (moment.vodId !== vodId) errors.push(`moments[${index}].vodId must match submission vodId.`)
    }
  }

  return errors.length > 0 ? { submission: null, errors } : { submission: value, errors: [] }
}

export function reviewFileNameForVodId(vodId) {
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(vodId)) {
    throw new Error(`Unsafe VOD id for review filename: ${vodId}`)
  }
  return `${vodId}.json`
}

export function detectReviewConflicts(submission, existingSubmissions, replacingVodId = null) {
  const errors = []
  const existingMomentOwners = new Map()

  for (const existing of existingSubmissions) {
    if (existing.vodId === replacingVodId) continue
    if (existing.vodId === submission.vodId) {
      errors.push(`A checked-in review already owns VOD ${submission.vodId}. Use --replace to update it.`)
    }
    for (const moment of existing.moments) existingMomentOwners.set(moment.id, existing.vodId)
  }

  for (const moment of submission.moments) {
    const owner = existingMomentOwners.get(moment.id)
    if (owner) errors.push(`Moment id ${moment.id} already belongs to reviewed VOD ${owner}.`)
  }

  return errors
}

export function renderReviewIndex(fileNames) {
  const sorted = [...fileNames].sort((a, b) => a.localeCompare(b))
  const header = [
    "import type { ProReviewSubmission } from '../../lib/proLabReviewIntake'",
    '',
    '/**',
    ' * Generated by scripts/prolab-ingest-review.mjs.',
    ' * JSON is cast only for TypeScript import compatibility; the production',
    ' * evidence registry re-validates every record and fails invalid evidence closed.',
    ' */',
  ]

  if (sorted.length === 0) {
    return `${header.join('\n')}\nexport const proReviewedSubmissions: readonly ProReviewSubmission[] = []\n`
  }

  const imports = sorted.map((fileName, index) => `import review${index} from './${fileName}'`)
  const values = sorted.map((_, index) => `  review${index} as unknown as ProReviewSubmission,`)
  return `${imports.join('\n')}\n${header.join('\n')}\nexport const proReviewedSubmissions: readonly ProReviewSubmission[] = [\n${values.join('\n')}\n]\n`
}

function readSubmission(path) {
  let value
  try {
    value = JSON.parse(readFileSync(path, 'utf8'))
  } catch (error) {
    throw new Error(`Could not parse ${path}: ${error instanceof Error ? error.message : String(error)}`)
  }
  const parsed = validateSubmissionEnvelope(value)
  if (!parsed.submission) throw new Error(parsed.errors.join('\n'))
  return parsed.submission
}

function readCheckedInSubmissions(reviewDir) {
  if (!existsSync(reviewDir)) return []
  return readdirSync(reviewDir)
    .filter((fileName) => fileName.endsWith('.json'))
    .sort((a, b) => a.localeCompare(b))
    .map((fileName) => readSubmission(resolve(reviewDir, fileName)))
}

function parseArgs(argv) {
  const positional = argv.filter((arg) => !arg.startsWith('--'))
  const flags = new Set(argv.filter((arg) => arg.startsWith('--')))
  for (const flag of flags) {
    if (flag !== '--replace') throw new Error(`Unknown option: ${flag}`)
  }
  if (positional.length !== 1) {
    throw new Error('Usage: npm run prolab:ingest-review -- <review-submission.json> [--replace]')
  }
  return { inputPath: resolve(process.cwd(), positional[0]), replace: flags.has('--replace') }
}

function restore(path, previous) {
  if (previous === null) rmSync(path, { force: true })
  else writeFileSync(path, previous)
}

function rollbackReviewFiles(targetPath, previousTarget, indexPath, previousIndex) {
  const rollbackErrors = []
  for (const [path, previous] of [[targetPath, previousTarget], [indexPath, previousIndex]]) {
    try {
      restore(path, previous)
    } catch (error) {
      rollbackErrors.push(`${path}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
  return rollbackErrors
}

export function ingestReviewSubmission({
  inputPath,
  reviewDir = defaultReviewDir,
  indexPath = defaultIndexPath,
  replace = false,
  runQualityGate = true,
}) {
  const submission = readSubmission(inputPath)
  const fileName = reviewFileNameForVodId(submission.vodId)
  const targetPath = resolve(reviewDir, fileName)
  const targetExists = existsSync(targetPath)
  if (targetExists && !replace) {
    throw new Error(`Review ${submission.vodId} already exists. Re-run with --replace to update it.`)
  }

  const existingSubmissions = readCheckedInSubmissions(reviewDir)
  const conflicts = detectReviewConflicts(submission, existingSubmissions, replace ? submission.vodId : null)
  if (conflicts.length > 0) throw new Error(conflicts.join('\n'))

  mkdirSync(reviewDir, { recursive: true })
  const previousTarget = targetExists ? readFileSync(targetPath) : null
  const previousIndex = existsSync(indexPath) ? readFileSync(indexPath) : null

  try {
    writeFileSync(targetPath, `${JSON.stringify(submission, null, 2)}\n`, 'utf8')
    const reviewFiles = readdirSync(reviewDir).filter((entry) => entry.endsWith('.json'))
    writeFileSync(indexPath, renderReviewIndex(reviewFiles), 'utf8')

    if (runQualityGate) {
      const result = spawnSync('npm', ['run', 'check'], {
        cwd: repoRoot,
        stdio: 'inherit',
        shell: process.platform === 'win32',
      })
      if (result.status !== 0) {
        throw new Error('Production quality gate failed. Review import was rejected.')
      }
    }

    return { submission, targetPath, indexPath }
  } catch (error) {
    const rollbackErrors = rollbackReviewFiles(targetPath, previousTarget, indexPath, previousIndex)
    const message = error instanceof Error ? error.message : String(error)
    if (rollbackErrors.length > 0) {
      throw new Error(`${message}\nRollback also failed:\n${rollbackErrors.join('\n')}`)
    }
    throw new Error(`${message}\nReview import was rolled back.`)
  }
}

function main() {
  try {
    const args = parseArgs(process.argv.slice(2))
    const result = ingestReviewSubmission(args)
    console.log(`Accepted Pro Lab review: ${result.submission.vodId}`)
    console.log(`Checked in as: ${result.targetPath}`)
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  }
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) main()
